#!/usr/bin/env python3
"""Generate src/st3exe_data.c embedding the unpacked ST3U.EXE."""
import sys
data = open(sys.argv[1], 'rb').read()
with open(sys.argv[2], 'w') as f:
    f.write('/* generated by tools_embed.py from %s — unpacked Scream Tracker 3.21 executable */\n' % sys.argv[1])
    f.write('const unsigned int st3_exe_len = %d;\nconst unsigned char st3_exe[] = {\n' % len(data))
    for i in range(0, len(data), 24):
        f.write(','.join(str(b) for b in data[i:i+24]) + ',\n')
    f.write('};\n')
